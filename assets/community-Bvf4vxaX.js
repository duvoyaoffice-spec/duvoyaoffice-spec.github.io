  <p>
    <span class="duvoya-legal__num">1.1.</span> הכללים נועדו שכל אחד ואחת ירגישו בטוחים ומכובדים ב־DUVOYA (בעברית:
    דּוּווֹיָה). הם חלק מ<a href="/legal/terms">תנאי השימוש</a> ומחייבים כל משתמש, בשירות וגם במפגשים ובמסעות שנולדו בו,
    ככל שהם קשורים לשירות.
  </p>
